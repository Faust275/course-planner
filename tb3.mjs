import { chromium } from 'playwright';
const b = await chromium.launch();
const p = await (await b.newContext({ viewport: { width: 1280, height: 950 } })).newPage();
p.on('pageerror', e => console.log('PAGEERROR', e.message));
const wait = ms => p.waitForTimeout(ms);
await p.goto('http://127.0.0.1:8137/index.html', { waitUntil: 'networkidle' });
await p.waitForTimeout(900);
await p.evaluate(() => { const s = [...document.querySelectorAll('button')].find(x => x.textContent.trim() === '跳过'); if (s) s.click(); });
await p.waitForTimeout(300);
await p.evaluate((day) => {
  Store.addSleep({ date: day, start: '23:00', end: '07:00' });
  Store.addActivity({ date: day, start: '10:00', end: '11:00', name: '手动记的自习', type: 'study' });
  App.go('calendar');
}, await p.evaluate(() => DateUtil.toStr(DateUtil.today())));
await wait(700);
await p.locator('.cp-tb-cell').nth(36).click(); await wait(400);
await p.locator('.cp-tb-type', { hasText: '学习' }).click(); await wait(600);
console.log('C1', await p.evaluate((day) => Store.activitiesOf(day).filter(a => a.from === 'block'), await p.evaluate(() => DateUtil.toStr(DateUtil.today()))));
await p.locator('.cp-tb-cell').nth(38).click(); await wait(400);
const modalState = await p.evaluate(() => !!document.querySelector('.cp-modal'));
console.log('modal after cell click:', modalState);
await p.locator('.cp-modal .cp-segment button', { hasText: '2 小时' }).click(); await wait(250);
const segs = await p.evaluate(() => [...document.querySelectorAll('.cp-modal .cp-segment button')].map(b => b.className + ':' + b.textContent.trim()));
console.log('segs:', segs);
const types = await p.evaluate(() => [...document.querySelectorAll('.cp-tb-type')].map(b => b.textContent.trim()));
console.log('types:', types);
await p.locator('.cp-tb-type', { hasText: '运动' }).click(); await wait(600);
console.log('C2', await p.evaluate((day) => Store.activitiesOf(day).filter(a => a.from === 'block'), await p.evaluate(() => DateUtil.toStr(DateUtil.today()))));
await b.close();
